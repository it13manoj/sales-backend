async function seedMoreLeads() {
  console.log('🚀 Seeding additional Enterprise Leads into MySQL...');

  // Find demo organization
  const org = await prisma.organization.findFirst();
  if (!org) {
    console.error('❌ No organization found. Please run initial seed first.');
    return;
  }

  // Find default campaign if any
  const campaign = await prisma.campaign.findFirst({
    where: { organizationId: org.id },
  });

  let createdCount = 0;
  for (const item of SAMPLE_LEADS) {
    const customFields = {
      domain: item.companyDomain,
      mailProvider: item.mailProvider,
      employeeRange: item.employeeRange,
      estimatedRevenue: item.estimatedRevenue,
      foundedYear: item.foundedYear,
      headquarters: item.headquarters,
      techStack: item.techStack,
      logoUrl: `https://logo.clearbit.com/${item.companyDomain}`,
      fallbackLogoUrl: `https://www.google.com/s2/favicons?domain=${item.companyDomain}&sz=128`,
      companyLinkedinUrl: `https://www.linkedin.com/company/${item.companyName.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
      apolloVerified: true,
      dataSource: 'Apollo.io Enterprise Verified',
      isDeliverable: true,
      spfValid: true,
      dmarcValid: true,
      seniorityLevel: item.title.includes('Chief') || item.title.includes('CEO') || item.title.includes('CTO') ? 'C-Suite / Executive' : 'VP / Head',
      icpScore: item.score,
      enrichedAt: new Date().toISOString(),
    };

    await prisma.lead.upsert({
      where: {
        organizationId_email: {
          organizationId: org.id,
          email: item.email,
        },
      },
      update: {
        firstName: item.firstName,
        lastName: item.lastName,
        title: item.title,
        companyName: item.companyName,
        companyDomain: item.companyDomain,
        industry: item.industry,
        phone: item.phone,
        status: item.status as any,
        score: item.score,
        enriched: true,
        customFields: customFields as any,
      },
      create: {
        organizationId: org.id,
        campaignId: campaign ? campaign.id : null,
        firstName: item.firstName,
        lastName: item.lastName,
        email: item.email,
        title: item.title,
        companyName: item.companyName,
        companyDomain: item.companyDomain,
        industry: item.industry,
        phone: item.phone,
        status: item.status as any,
        score: item.score,
        enriched: true,
        customFields: customFields as any,
      },
    });

    createdCount++;
  }

  console.log(`✅ Successfully seeded ${createdCount} new Enterprise Leads into MySQL!`);
}

seedMoreLeads()
  .catch((e) => {
    console.error('Seed error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

